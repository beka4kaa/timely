export const TIPS: Tip[] = [
  ...REST.map((text) => ({ kind: "rest" as const, text })),
  ...FOCUS.map((text) => ({ kind: "focus" as const, text })),
];

/** Какие советы уместны сейчас: на перерыве про отдых, в фокусе про работу, до старта любые. */
export function tipsFor(mode: TipKind | "any"): number[] {
  return TIPS.map((tip, index) => ({ tip, index }))
    .filter(({ tip }) => mode === "any" || tip.kind === mode)
    .map(({ index }) => index);
}

/** Следующий совет: случайный из подходящих, но не тот, что на экране. */
export function nextTip(current: number | null, mode: TipKind | "any", random: () => number = Math.random): number {
  const pool = tipsFor(mode).filter((index) => index !== current);
  return pool[Math.floor(random() * pool.length)] ?? 0;
}

/** Совет как цитата в «ёлочках». Точку в конце убираем: внутри кавычек она лишняя. */
export function quoted(text: string): string {
  const body = text.replace(/\.$/, "");
  return getLocale() === "en" ? `“${body}”` : `«${body}»`;
}

