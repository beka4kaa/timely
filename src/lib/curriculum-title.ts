/**
 * curriculum-title.ts — читаемое имя книги из имени файла.
 *
 * `Document.title` по умолчанию равен очищенному имени загруженного файла, а
 * файлы у людей называются так:
 *
 *     1741867504__-mehanika_-10-klass_-mjakishev-g_-ja_-2022
 *
 * В каталоге это занимало две строки и ломало любую вёрстку. Здесь строка
 * приводится к виду «Mehanika 10 klass mjakishev g ja 2022».
 *
 * **Только для показа.** Хранимый заголовок не переписывается: это данные
 * пользователя, и подменять их эвристикой нельзя — тем более что переименование
 * руками напрашивается отдельной задачей и должно побеждать любую догадку.
 *
 * **Транслитерации нет.** Латиница остаётся латиницей: «mehanika» → «механика»
 * выглядит заманчиво ровно до первого имени собственного, которое такой
 * пересчёт изуродует. Лучше честная латиница, чем красивая ошибка.
 */

/** Ведущая метка времени, которую добавляет загрузчик. */
const LEADING_TIMESTAMP = /^\d{8,}[\s_-]*/;
const EXTENSION = /\.(pdf|epub|djvu|fb2|txt)$/i;
const SEPARATORS = /[\s_-]+/g;

export function cleanDocumentTitle(raw: string): string {
  const source = (raw || "").trim();
  if (!source) return "";

  const cleaned = source
    .replace(EXTENSION, "")
    .replace(LEADING_TIMESTAMP, "")
    .replace(SEPARATORS, " ")
    .trim();

  // Если чистка съела всё (имя состояло из одной метки времени), исходная
  // строка полезнее пустоты: по ней хотя бы можно отличить одну книгу от другой.
  if (!cleaned) return source;

  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
}
