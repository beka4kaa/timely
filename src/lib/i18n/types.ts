// Типы словарей. Отдельным файлом, чтобы словари `en/*` не импортировали сам модуль
// перевода и не получилось круга.

export type Locale = "ru" | "en";

/**
 * Словарь одного языка: русский текст из кода → перевод.
 *
 * Подстановки пишутся в фигурных скобках и должны совпадать с русскими: «Осталось {n} мин»
 * → «{n} min left». Склонение (`plural`) лежит под ключом «форма1|форма2|форма5», а перевод —
 * «единственное|множественное»: «урок|урока|уроков» → «lesson|lessons».
 */
export type Dictionary = Record<string, string>;
