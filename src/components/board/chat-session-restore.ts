/**
 * Чистая логика восстановления сохранённой сессии чата.
 *
 * Вынесена из `ai-chat.tsx` отдельным модулем ровно затем, чтобы её можно было
 * покрыть тестом: сам `ai-chat.tsx` — тяжёлый клиентский компонент с JSX, и в
 * `node:test` его не импортировать.
 */

/** Минимум от `ChatMessage`, который нужен этой логике. */
export interface RestoreCandidateMessage {
  /** Служебные события интейка плана: «План принят · можно начинать» и т.п. */
  planningEvent?: boolean;
}

/**
 * Есть ли на экране хоть одно сообщение, автором которого является ПОЛЬЗОВАТЕЛЬ
 * (или ответ модели на него), а не интейк плана.
 *
 * Нужна для решения «перезаписывать ли текущий экран восстановленной сессией».
 * Раньше на этом месте стояла проверка `messages.length > 0`, и она ломала
 * восстановление НАСМЕРТЬ: план поднимается на монтировании синхронным
 * setState и сразу кладёт в `messages` служебный баннер, а восстановление
 * сессии — сетевой запрос. Сеть синхронный setState не обгоняет никогда,
 * поэтому любой заход считался «грязным», восстановление отменялось, и
 * автосейв заводил ещё одну сессию. История копилась в базе, но на экран не
 * возвращалась — снаружи это выглядело как «чаты не сохраняются».
 */
export function hasUserAuthoredMessage(
  messages: readonly RestoreCandidateMessage[],
): boolean {
  return messages.some((message) => !message.planningEvent);
}

/**
 * Есть ли на доске несохранённая работа ученика.
 *
 * Второй критерий «грязного» экрана рядом с `hasUserAuthoredMessage`. Раньше
 * восстановление смотрело только на сообщения, и медленно доехавший
 * mount-restore бил дважды: `restoreCanvas` затирал уже нарисованное, а
 * `lastSavedCanvasRef` переставлялся на серверный снимок — из-за чего уже
 * взведённый автосейв упирался в проверку «ничего не изменилось» и не
 * отправлял запрос вообще. Работа исчезала бесследно.
 *
 * @param serializedNow — снимок доски прямо сейчас (`serializeCanvas`).
 * @param lastSaved — последний успешно сохранённый снимок; `null`, если сессия
 * ещё ни разу не сохранялась.
 * @param emptyCanvas — как выглядит пустая доска в той же сериализации.
 */
export function boardHasUnsavedWork(
  serializedNow: string,
  lastSaved: string | null,
  emptyCanvas: string,
): boolean {
  return serializedNow !== (lastSaved ?? emptyCanvas);
}
