// Страницы, на которых панели вопросов быть не должно.
//
// Обе причины — чужой чат в том же углу экрана:
//
// «Тьютор» — сам по себе разговор во весь экран, и чат внутри чата бессмыслен.
// Доска живёт в `fixed inset-0 z-[100]` со своим AI-тьютором справа, своей
// шапкой и своим сгибом; панель идёт `z-[115]` и просто ложится поверх.
//
// Список нужен не только самой панели: `AskRailProvider` держит ширину, на
// которую сдвинута страница, и без него контент уехал бы вправо под панель,
// которой нет.

const RAIL_FREE_ROUTES = [
  "/dashboard/chat",
  "/dashboard/whiteboard",
  // Редиректит на доску, но панель успевает моргнуть до перехода.
  "/dashboard/board",
];

export function isRailFreeRoute(pathname: string): boolean {
  return RAIL_FREE_ROUTES.some(
    (route) => pathname === route || pathname.startsWith(`${route}/`),
  );
}
