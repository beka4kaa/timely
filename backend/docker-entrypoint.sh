#!/bin/sh
set -e

# Веб-контейнер не стартует без настоящего SECRET_KEY. В settings.py для локальной
# разработки лежит значение по умолчанию, и оно есть в репозитории: им нельзя
# подписывать ничего в проде. Проверка здесь, а не в settings.py, потому что
# `collectstatic` при сборке образа работает вообще без переменных окружения.
if [ "${RUN_MIGRATIONS:-1}" = "1" ] && [ -z "${SECRET_KEY:-}" ]; then
    echo "[entrypoint] SECRET_KEY не задан, запуск отменён" >&2
    exit 1
fi

# Миграции ДО старта gunicorn.
#
# Зачем этот файл вообще появился: раньше Dockerfile запускал gunicorn напрямую,
# и `manage.py migrate` не выполнялся при деплое НИКОГДА. Код с новыми полями
# модели уезжал в прод, а схема базы оставалась старой — каждый запрос к
# изменившейся таблице падал в 500. Ровно так сломался /api/chat-sessions после
# PR #8: модель ChatSession получила mode/status/policy и т.д., миграция 0007
# лежала в репозитории, но на боевой базе применена не была.
#
# `migrate` идемпотентен: если применять нечего, он просто ничего не делает.
#
# ВАЖНО про несколько реплик: при одновременном старте двух и более контейнеров
# они могут начать миграцию параллельно, и проигравший упадёт на «column already
# exists». Контейнер после этого перезапустится и увидит схему уже накатанной,
# то есть ситуация самозалечивается, но в логах будет шумно. Если реплик станет
# больше одной, миграции надо выносить в отдельный release-шаг, а не в старт.
#
# `RUN_MIGRATIONS=0` нужен воркеру Celery: он поднимается из ТОГО ЖЕ образа, и
# без флага web-контейнер и воркер начинали бы миграцию одновременно при каждом
# деплое. Схему меняет ровно один процесс — web.
if [ "${RUN_MIGRATIONS:-1}" = "1" ]; then
    echo "[entrypoint] applying database migrations..."
    python manage.py migrate --noinput
    # CACHES = DatabaseCache: без cache_table любой cache.get() падает в 500.
    # Команда идемпотентна — существующую таблицу не трогает.
    python manage.py createcachetable
else
    echo "[entrypoint] RUN_MIGRATIONS=0 — миграции пропущены"
fi

echo "[entrypoint] starting: $*"
exec "$@"
