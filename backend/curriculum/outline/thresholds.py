"""Пороги доверия к структуре книги — в одном месте и под тестами.

Числа здесь не косметические: от них зависит, попадёт ли раздел в учебную
программу. Разбросанные по коду константы через месяц разъезжаются, и тогда
детектор считает страницу оглавлением по одному порогу, а планировщик доверяет
ей по другому.
"""

from __future__ import annotations

# ── Доверие к готовой структуре ──────────────────────────────────────────────
#
# high   — использовать молча;
# medium — использовать, но пометить предупреждением;
# ниже   — в планирование не пускать, оставить как физическую разметку.
CONFIDENCE_HIGH = 0.85
CONFIDENCE_MEDIUM = 0.60


def confidence_band(value: float) -> str:
    if value >= CONFIDENCE_HIGH:
        return "high"
    if value >= CONFIDENCE_MEDIUM:
        return "medium"
    return "low"


# ── Детектор страниц оглавления ──────────────────────────────────────────────

# Страница считается оглавлением, начиная с этого веса сигналов.
TOC_PAGE_CONFIDENCE = 0.55
# Минимум записей «название … номер» на странице. Одна-две встречаются на любой
# странице с формулами, поэтому порог не может быть низким.
TOC_MIN_ENTRIES = 4
# Доля строк с номером в конце, при которой страница выглядит как оглавление.
TOC_MIN_ENTRY_RATIO = 0.35
# Сколько страниц с начала и с конца книги вообще рассматривать. Оглавление
# бывает и там и там (у Мякишева — на 508-й из 513), но в середине книги его
# не бывает, а вот таблица с числами — сколько угодно.
TOC_HEAD_PAGES = 20
TOC_TAIL_PAGES = 20

# ── Сверка печатных и PDF-страниц ────────────────────────────────────────────

# Сколько записей должно подтвердить одно и то же смещение, чтобы ему верить.
OFFSET_MIN_VOTES = 3
# Насколько далеко от ожидаемой страницы ищем заголовок в теле книги.
VERIFY_PAGE_TOLERANCE = 2
# Порог похожести названий при сверке (SequenceMatcher).
VERIFY_TITLE_RATIO = 0.72

# Уверенность узла, который есть в оглавлении, но чей заголовок не нашёлся в
# теле на ожидаемой странице. Выше `CONFIDENCE_MEDIUM` намеренно: оглавление
# напечатано в книге, и неудача сверки — это чаще всего слабость матчера
# (параграф начался в середине страницы), а не отсутствие раздела.
UNVERIFIED_CONFIDENCE = 0.65
