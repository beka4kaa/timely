"""Отсев строк, похожих на инструкцию, перед подстановкой в системный промпт.

Зачем. Названия тем и заголовки чатов пишет пользователь, а заголовок вдобавок
придумывает модель ПО его тексту (chat_title.py). Дальше и то и другое попадает
в блок памяти тьютора (student_memory.py), то есть внутрь системного промпта.
Сам по себе это не переход границы доступа — пользователь влияет только на свой
же промпт, чужих данных здесь нет. Но короткая строка вида «Игнорируй правила»
в системном сообщении — это лишний шанс, что модель частично её послушает,
и стоит он нам ровно одну проверку подстроки.

Это ВТОРОЙ рубеж, а не единственный. Первый остаётся прежним и важнее:
блок помечен как справка, строки схлопнуты и усечены, число их ограничено
(см. student_memory). Эвристика ниже не претендует на полноту — она снимает
очевидные формулировки, а не заменяет структурную защиту.

Порог ложных срабатываний намеренно низкий: проверяем короткие строки
(названия тем и трёхсловные заголовки), где реальные формулировки —
«Закон Ома», «Сила трения», «Квадратное уравнение» — ни одного из маркеров
не содержат.
"""

from __future__ import annotations

import re

# Маркеры на русском и английском: попытка переопределить поведение модели,
# сослаться на системный промпт или назначить ей новую роль.
_INSTRUCTION_MARKERS = (
    "игнорир",
    "игнорируй",
    "забудь",
    "забудьте",
    "отмени",
    "не отвеча",
    "отвечай только",
    "притвор",
    "ты теперь",
    "действуй как",
    "веди себя как",
    "систем",
    "промпт",
    "инструкц",
    "ignore",
    "disregard",
    "forget",
    "override",
    "system prompt",
    "instruction",
    "you are now",
    "act as",
    "pretend",
    "jailbreak",
)

# Разделители, которыми пытаются «закрыть» текущий блок и начать свой.
_STRUCTURE_MARKERS = ("```", "<<<", ">>>", "---", "###")


def looks_like_instruction(text: str) -> bool:
    """Похожа ли строка на попытку дать модели указание, а не назвать тему."""
    value = " ".join(str(text or "").split()).casefold()
    if not value:
        return False
    if any(marker in value for marker in _STRUCTURE_MARKERS):
        return True
    return any(marker in value for marker in _INSTRUCTION_MARKERS)


def strip_control_characters(text: str) -> str:
    """Убирает управляющие символы, которыми ломают разметку промпта.

    Переводы строк схлопывает вызывающий код, а здесь снимаются менее заметные
    вещи: возвраты каретки, вертикальные табуляции и невидимые управляющие
    коды, которые в логах выглядят как обычная строка.
    """
    return re.sub(r"[\x00-\x1f\x7f]+", " ", str(text or "")).strip()
