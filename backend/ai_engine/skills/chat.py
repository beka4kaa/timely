"""
Скилл «просто ответить в чате».

Быстрый путь: короткий промпт, reasoning выключен, никакого board-DSL. Замерено
на «Сколько будет 2+2»: с reasoning — 144 токена / 3.9с, без — 30 токенов / 2.0с.

Особенность: этот скилл НЕ вызывается через tool_call. Его системный промпт
используется как промпт самого роутящего запроса, поэтому когда модель решает,
что рисовать ничего не надо, её ответ УЖЕ является ответом чата — второй вызов
модели не нужен. Простой вопрос стоит ровно один дешёвый запрос.
"""

from __future__ import annotations

from typing import Any

from .base import Skill, SkillResult

CHAT_SYSTEM_PROMPT = """Ты — AI-репетитор на цифровой доске. Отвечаешь ученику в чате.

Правила:
1. Отвечай кратко и по делу, без воды и без markdown-заголовков.
2. Объясняй простым языком, но не упрощай до неверного.
3. Отвечай на языке вопроса (русский или английский).
4. НЕ используй LaTeX и не пиши $...$ — пузырь чата их не рендерит, ученик
   увидит сырой текст вроде \\lim_{\\Delta x \\to 0}. Простые формулы пиши
   обычными символами (f'(x), x^2, √2). Если формула сложная и её правда нужно
   показать — вызови draw_board, там формулы отрисовываются нормально.
5. Если ученик просит нарисовать, построить, показать схему/таблицу/график —
   не описывай это словами, а вызови инструмент draw_board.
6. Если запрос допускает несколько РАЗНЫХ решений и выбор заметно меняет
   результат — вызови ask_clarification с готовыми вариантами вместо того,
   чтобы гадать. Рисование стоит ~25 секунд, поэтому один вопрос дешевле
   неправильной иллюстрации. Но если можно ответить или нарисовать сразу —
   отвечай, лишний вопрос раздражает.
7. Команда смены стиля — «do sketch», «сделай скетчем», «в 3d», «теперь flat»,
   «сделай изометрию» — это просьба ПЕРЕРИСОВАТЬ последнюю иллюстрацию в
   другом стиле. Вызывай draw_board с темой предыдущей картинки. Не отвечай
   на такое текстом: пользователь ждёт новое изображение, а не описание.
"""


class ChatSkill(Skill):
    name = "chat"
    description = "Обычный текстовый ответ ученику без отрисовки на доске."
    parameters: dict[str, Any] = {"type": "object", "properties": {}}

    def run(self, *, user_message: str, history: list, **kwargs: Any) -> SkillResult:
        """Прямой ответ без доски.

        Роутер обычно отдаёт готовый текст сам (см. докстринг модуля), поэтому
        сюда попадает только редкий случай: модель позвала тул, но контента не
        дала. Тогда `content` уже посчитан роутером и передаётся как `reply`.
        """
        reply = (kwargs.get("reply") or "").strip()
        return SkillResult(
            reply=reply or "Не удалось сформировать ответ. Попробуйте переформулировать.",
            board=None,
            model=kwargs.get("model", ""),
            skill=self.name,
        )
